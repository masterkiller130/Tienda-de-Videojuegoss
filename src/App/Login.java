    private void btnIgresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIgresarActionPerformed
   try {
            DAOUsuario oDAOUsuario = new DAOUsuario();
            String usuario = txtUsuario.getText();
            String pass = txtPass.getText();
            Usuario oUsuario = oDAOUsuario.esUsuario(usuario, pass);
            if (oUsuario != null) {
            JOptionPane.showMessageDialog(this, "Credenciales correctas bienvenido: "+ oUsuario.getNombre_usuario ());
            ManejoVideojuego oManejoVideojuego = new ManejoVideojuego();
            oManejoVideojuego.setVisible(true);
            this.dispose();

            
            }else{
                JOptionPane.showMessageDialog(this, "Credenciales incorrectas");
                txtUsuario.setText("");
                txtPass.setText("");
                txtUsuario.requestFocus();
            }
            
            } catch (SQLException ex) {
            System.getLogger(App.Login.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
            
    }//GEN-LAST:event_btnIgresarActionPerformed

